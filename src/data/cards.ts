const getPopularityScore = (id: string, name: string): number => {
  const normId = id.toLowerCase();
  if (POPULARITY_MAP[normId] !== undefined) {
    return POPULARITY_MAP[normId];
  }
  for (const [key, val] of Object.entries(POPULARITY_MAP)) {
    if (normId.includes(key) || key.includes(normId)) {
      return val;
    }
  }
  let hash = 0;
  for (let i = 0; i < name.length; i++) {
    hash = name.charCodeAt(i) + ((hash << 5) - hash);
  }
  return 30 + Math.abs(hash % 51);
};

const distributePower = (targetPower: number, original: { top: number, right: number, bottom: number, left: number }) => {
  const originalSum = original.top + original.right + original.bottom + original.left;
  let top = 1;
  let right = 1;
  let bottom = 1;
  let left = 1;
  if (originalSum > 0) {
    top = Math.round((original.top / originalSum) * targetPower);
    right = Math.round((original.right / originalSum) * targetPower);
    bottom = Math.round((original.bottom / originalSum) * targetPower);
    left = Math.round((original.left / originalSum) * targetPower);
  } else {
    const base = Math.floor(targetPower / 4);
    top = base;
    right = base;
    bottom = base;
    left = targetPower - (base * 3);
  }
  top = Math.max(1, Math.min(10, top));
  right = Math.max(1, Math.min(10, right));
  bottom = Math.max(1, Math.min(10, bottom));
  left = Math.max(1, Math.min(10, left));
  let currentSum = top + right + bottom + left;
  let attempts = 0;
  while (currentSum !== targetPower && attempts < 100) {
    attempts++;
    const diff = targetPower - currentSum;
    if (diff > 0) {
      if (top < 10) { top++; currentSum++; }
      else if (right < 10) { right++; currentSum++; }
      else if (bottom < 10) { bottom++; currentSum++; }
      else if (left < 10) { left++; currentSum++; }
      else { break; }
    } else {
      if (top > 1) { top--; currentSum--; }
      else if (right > 1) { right--; currentSum--; }
      else if (bottom > 1) { bottom--; currentSum--; }
      else if (left > 1) { left--; currentSum--; }
      else { break; }
    }
  }
  return { top, right, bottom, left };
};

